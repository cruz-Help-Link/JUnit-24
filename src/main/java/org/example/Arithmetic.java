package org.example;

public class Arithmetic {
    public int findGreatest(int a, int b) {
        if (a > b) {
            return a;
        }
        else return b;
    }

    public String toUpper(String value) {
        return value.toUpperCase();
    }
    public String toLower(String value) {
        return value.toLowerCase();
    }

}
